package com.vbforge.practice.practice_10_wrapper_utility_methods;

/**
 * Integer constants and small static helpers.
 */
public class IntegerConstantsAndHelpersDemo {

    public static void main(String[] args) {
        System.out.println("MAX_VALUE:     " + Integer.MAX_VALUE);
        System.out.println("MIN_VALUE:     " + Integer.MIN_VALUE);
        System.out.println("compare(3, 5): " + Integer.compare(3, 5));
        System.out.println("max(3, 7):     " + Integer.max(3, 7));
        System.out.println("sum(3, 7):     " + Integer.sum(3, 7));
    }
}
